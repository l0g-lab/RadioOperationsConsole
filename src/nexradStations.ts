/** Nearest NEXRAD station code to a coordinate, computed entirely offline (RADAR-015). */
export function nearestNexradStation(lat: number, lon: number): string {
  let best = NEXRAD_STATIONS[0];
  let bestDist = Infinity;
  for (const station of NEXRAD_STATIONS) {
    const dist = haversineKm(lat, lon, station[1], station[2]);
    if (dist < bestDist) {
      bestDist = dist;
      best = station;
    }
  }
  return best[0];
}
